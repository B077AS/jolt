package io.github.b077as.jolt.internal;

import java.lang.reflect.GenericArrayType;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.RecordComponent;
import java.lang.reflect.Type;
import java.lang.reflect.TypeVariable;
import java.lang.reflect.WildcardType;
import java.util.ArrayList;
import java.util.Collection;
import java.util.Comparator;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.TreeMap;
import java.util.concurrent.CompletionStage;
import java.util.concurrent.Flow;
import java.util.concurrent.Future;
import java.lang.annotation.Annotation;

/**
 * Writes TypeScript declarations for the methods of an {@code Rpc}: one interface per record, a type per enum, and a typed
 * {@code window.jolt}. The shapes follow what {@link BasicJson} writes (the built-in codec): records by component name, enums as their
 * names, {@code Optional} as the value or null, maps as objects, collections and arrays as arrays, numbers (also {@code long}) as
 * {@code number}, and text-like values (UUID, URI, {@code java.time}, paths) as strings. A JSON library with other conventions
 * (renamed properties, other date formats) needs declarations of its own. Whatever it does not know it writes as {@code unknown}.
 *
 * <p>A reference-type record component may be null, so it is written {@code name?: T | null}; a primitive, or a component annotated
 * with an annotation named {@code NonNull}, {@code Nonnull} or {@code NotNull} (whichever library it comes from), is required.
 * Annotations are matched by simple name, so Jolt needs no dependency on the library that has them, and they must be kept at run
 * time (Lombok's {@code @NonNull} is not, so it has no effect here). To avoid annotating every component, mark the record, a class
 * around it, its package or its module {@code @NullMarked} (JSpecify): then every component is required unless it is
 * {@code @Nullable}; the closest {@code @NullMarked} or {@code @NullUnmarked} wins. {@code @Nullable} always wins on a component.
 */
public final class TypeScript {

    /** One method: its name, what it reads the parameters as ({@code void.class} for none, {@code null} if unknown) and returns. */
    public record Endpoint(String name, Type params, Type result) {
    }

    /** A rendered type; {@code union} when it must be parenthesised as an array element, {@code nullable} when it already allows null. */
    private record Ts(String text, boolean union, boolean nullable) {
        static final Ts UNKNOWN = new Ts("unknown", false, false);

        static Ts plain(String text) {
            return new Ts(text, false, false);
        }
    }

    private static final Set<String> NON_NULL = Set.of("NonNull", "Nonnull", "NotNull");
    private static final Set<String> NULLABLE = Set.of("Nullable");
    private static final Set<String> NULL_MARKED = Set.of("NullMarked");
    private static final Set<String> NULL_UNMARKED = Set.of("NullUnmarked");

    private final Map<Class<?>, String> names = new HashMap<>();
    private final Set<String> taken = new HashSet<>();
    private final TreeMap<String, String> definitions = new TreeMap<>();

    private TypeScript() {
    }

    public static String generate(Collection<Endpoint> endpoints) {
        return new TypeScript().write(endpoints);
    }

    private String write(Collection<Endpoint> endpoints) {
        List<Endpoint> sorted = new ArrayList<>(endpoints);
        sorted.sort(Comparator.comparing(Endpoint::name));
        StringBuilder calls = new StringBuilder();
        StringBuilder streams = new StringBuilder();
        for (Endpoint endpoint : sorted) {
            String params = endpoint.params() == null ? "JoltUntyped"
                    : endpoint.params() == void.class ? "void" : type(endpoint.params(), Set.of()).text();
            Type result = endpoint.result();
            Type item = streamItem(result);
            if (item != NOT_A_STREAM) {
                streams.append("  ").append(BasicJson.quote(endpoint.name())).append(": { params: ").append(params)
                        .append("; item: ").append(item == null ? "unknown" : type(item, Set.of()).text()).append(" };\n");
            } else {
                calls.append("  ").append(BasicJson.quote(endpoint.name())).append(": { params: ").append(params)
                        .append("; result: ").append(resultText(result)).append(" };\n");
            }
        }
        StringBuilder out = new StringBuilder();
        out.append("// Generated by Jolt from the methods registered with Rpc. Do not edit: regenerate with Rpc.writeTypeScript(path).\n");
        out.append("// The shapes are those of JsonCodec.basic(); a JSON library that writes other names or formats needs its own declarations.\n\n");
        for (String definition : definitions.values()) {
            out.append(definition).append('\n');
        }
        out.append("/** What each method takes and returns, for jolt.call. */\n");
        out.append("export interface JoltMethods {\n").append(calls).append("}\n\n");
        out.append("/** The streaming methods: what they take and one item, for jolt.stream. */\n");
        out.append("export interface JoltStreams {\n").append(streams).append("}\n\n");
        out.append("/** What a method registered without its parameter type may be sent. */\n");
        out.append("export type JoltUntyped = string | number | boolean | object | null | void;\n\n");
        out.append("export interface JoltCallOptions {\n");
        out.append("  signal?: AbortSignal;\n  timeout?: number;\n  onProgress?: (data: unknown) => void;\n}\n\n");
        out.append("export interface JoltStreamOptions {\n  signal?: AbortSignal;\n}\n\n");
        out.append("/** The arguments after the method: the parameters may be left out when the method takes none (or accepts nothing). */\n");
        out.append("export type JoltArgs<P, O> = [void] extends [P] ? [params?: P, options?: O] : [params: P, options?: O];\n\n");
        out.append("export interface Jolt {\n");
        out.append("  call<M extends keyof JoltMethods>(method: M, ...args: JoltArgs<JoltMethods[M][\"params\"], JoltCallOptions>): Promise<JoltMethods[M][\"result\"]>;\n");
        out.append("  stream<M extends keyof JoltStreams>(method: M, ...args: JoltArgs<JoltStreams[M][\"params\"], JoltStreamOptions>): AsyncIterableIterator<JoltStreams[M][\"item\"]>;\n");
        out.append("  onEvent<T = unknown>(name: string, callback: (data: T) => void): () => void;\n");
        out.append("  postMessage(message: string): void;\n");
        out.append("  onMessage(callback: (message: string) => void): () => void;\n");
        out.append("}\n\n");
        out.append("declare global {\n  interface Window {\n    jolt: Jolt;\n  }\n}\n");
        return out.toString();
    }

    // ---------------------------------------------------------------- methods

    private static final Type NOT_A_STREAM = new Type() {
    };

    /** The item type of a streaming result, {@code null} for items of unknown type, or {@link #NOT_A_STREAM}. */
    private static Type streamItem(Type result) {
        Class<?> raw = rawOf(result);
        if (raw == null || !(Flow.Publisher.class == raw || io.github.b077as.jolt.RpcStream.class == raw)) {
            return NOT_A_STREAM;
        }
        return result instanceof ParameterizedType p ? p.getActualTypeArguments()[0] : null;
    }

    private String resultText(Type result) {
        Type unwrapped = result;
        Class<?> raw = rawOf(unwrapped);
        if (raw != null && (CompletionStage.class.isAssignableFrom(raw) || Future.class.isAssignableFrom(raw))) {
            unwrapped = unwrapped instanceof ParameterizedType p ? p.getActualTypeArguments()[0] : null;
        }
        if (unwrapped == void.class || unwrapped == Void.class) {
            return "void";
        }
        return unwrapped == null ? "unknown" : type(unwrapped, Set.of()).text();
    }

    private static Class<?> rawOf(Type type) {
        if (type instanceof Class<?> c) {
            return c;
        }
        if (type instanceof ParameterizedType p && p.getRawType() instanceof Class<?> c) {
            return c;
        }
        return null;
    }

    // ---------------------------------------------------------------- types

    private Ts type(Type type, Set<String> variables) {
        if (type instanceof Class<?> c) {
            return ofClass(c);
        }
        if (type instanceof ParameterizedType p) {
            return parameterized(p, variables);
        }
        if (type instanceof GenericArrayType g) {
            return array(type(g.getGenericComponentType(), variables));
        }
        if (type instanceof TypeVariable<?> v) {
            return variables.contains(v.getName()) ? Ts.plain(v.getName()) : Ts.UNKNOWN;
        }
        if (type instanceof WildcardType w) {
            Type[] upper = w.getUpperBounds();
            return upper.length == 1 && upper[0] != Object.class ? type(upper[0], variables) : Ts.UNKNOWN;
        }
        return Ts.UNKNOWN;
    }

    private Ts ofClass(Class<?> c) {
        if (c.isArray()) {
            return array(ofClass(c.getComponentType()));
        }
        if (c == boolean.class || c == Boolean.class) {
            return Ts.plain("boolean");
        }
        if (c == char.class || c == Character.class || CharSequence.class.isAssignableFrom(c) || isText(c)) {
            return Ts.plain("string");
        }
        if (c.isPrimitive() && c != void.class || Number.class.isAssignableFrom(c)) {
            return Ts.plain("number");
        }
        if (c == void.class || c == Void.class) {
            return Ts.plain("void");
        }
        if (c.isEnum()) {
            return Ts.plain(enumName(c));
        }
        if (c.isRecord()) {
            return Ts.plain(recordName(c) + (c.getTypeParameters().length == 0 ? "" : "<" + "unknown, ".repeat(c.getTypeParameters().length - 1) + "unknown>"));
        }
        if (Map.class.isAssignableFrom(c)) {
            return Ts.plain("Record<string, unknown>");
        }
        if (Iterable.class.isAssignableFrom(c)) {
            return array(Ts.UNKNOWN);
        }
        return Ts.UNKNOWN;
    }

    private Ts parameterized(ParameterizedType p, Set<String> variables) {
        if (!(p.getRawType() instanceof Class<?> raw)) {
            return Ts.UNKNOWN;
        }
        Type[] arguments = p.getActualTypeArguments();
        if (raw.isRecord()) {
            if (arguments.length == 0) {
                return ofClass(raw);
            }
            StringBuilder reference = new StringBuilder(recordName(raw)).append('<');
            for (int i = 0; i < arguments.length; i++) {
                reference.append(i > 0 ? ", " : "").append(type(arguments[i], variables).text());
            }
            return Ts.plain(reference.append('>').toString());
        }
        if (raw == Optional.class && arguments.length == 1) {
            return new Ts(type(arguments[0], variables).text() + " | null", true, true);
        }
        if (Map.class.isAssignableFrom(raw) && arguments.length == 2) {
            Type key = arguments[0];
            String value = type(arguments[1], variables).text();
            if (key instanceof Class<?> k && k.isEnum()) {
                return Ts.plain("Partial<Record<" + enumName(k) + ", " + value + ">>");
            }
            return Ts.plain("Record<string, " + value + ">");
        }
        if (Iterable.class.isAssignableFrom(raw) && arguments.length == 1) {
            return array(type(arguments[0], variables));
        }
        if ((CompletionStage.class.isAssignableFrom(raw) || Future.class.isAssignableFrom(raw)) && arguments.length == 1) {
            return type(arguments[0], variables);
        }
        return Ts.UNKNOWN;
    }

    private static Ts array(Ts element) {
        return Ts.plain(element.union() ? "(" + element.text() + ")[]" : element.text() + "[]");
    }

    /** Value types BasicJson writes as their {@code toString()}. */
    private static boolean isText(Class<?> c) {
        return c == java.util.UUID.class || c == java.net.URI.class || c.getName().startsWith("java.time.")
                || java.nio.file.Path.class.isAssignableFrom(c);
    }

    // ---------------------------------------------------------------- named types

    private String enumName(Class<?> c) {
        String known = names.get(c);
        if (known != null) {
            return known;
        }
        String name = claim(c);
        StringBuilder union = new StringBuilder();
        for (Object constant : c.getEnumConstants()) {
            union.append(union.isEmpty() ? "" : " | ").append(BasicJson.quote(((Enum<?>) constant).name()));
        }
        definitions.put(name, "export type " + name + " = " + (union.isEmpty() ? "never" : union) + ";\n");
        return name;
    }

    private String recordName(Class<?> c) {
        String known = names.get(c);
        if (known != null) {
            return known;
        }
        String name = claim(c);
        definitions.put(name, ""); // a record that refers to itself finds its name already
        List<String> parameters = new ArrayList<>();
        for (TypeVariable<?> variable : c.getTypeParameters()) {
            parameters.add(variable.getName());
        }
        Set<String> scope = Set.copyOf(parameters);
        StringBuilder body = new StringBuilder("export interface ").append(name);
        if (!parameters.isEmpty()) {
            body.append('<').append(String.join(", ", parameters)).append('>');
        }
        body.append(" {\n");
        for (RecordComponent component : c.getRecordComponents()) {
            Ts type = type(component.getGenericType(), scope);
            boolean nullable = type.nullable() || (!component.getType().isPrimitive() && !required(c, component));
            body.append("  ").append(component.getName()).append(nullable ? "?" : "").append(": ").append(type.text())
                    .append(nullable && !type.nullable() ? " | null" : "").append(";\n");
        }
        definitions.put(name, body.append("}\n").toString());
        return name;
    }

    /** Whether a reference-type component is always present: {@code @Nullable} says no, {@code @NonNull} says yes, else the surrounding {@code @NullMarked} decides. */
    private static boolean required(Class<?> record, RecordComponent component) {
        if (hasAnyOf(component.getAnnotations(), component.getAnnotatedType().getAnnotations(), NULLABLE)) {
            return false;
        }
        if (hasAnyOf(component.getAnnotations(), component.getAnnotatedType().getAnnotations(), NON_NULL)) {
            return true;
        }
        return nullMarked(record);
    }

    /** The closest {@code @NullMarked} / {@code @NullUnmarked} around the record: its classes from the inside out, then its package, then its module. */
    private static boolean nullMarked(Class<?> record) {
        for (Class<?> c = record; c != null; c = c.getEnclosingClass()) {
            Boolean decided = marker(c.getAnnotations());
            if (decided != null) {
                return decided;
            }
        }
        Package pkg = record.getPackage();
        Boolean decided = pkg == null ? null : marker(pkg.getAnnotations());
        if (decided == null) {
            decided = marker(record.getModule().getAnnotations());
        }
        return decided != null && decided;
    }

    /** {@code true} for a {@code NullMarked} among these annotations, {@code false} for {@code NullUnmarked}, {@code null} for neither. */
    private static Boolean marker(Annotation[] annotations) {
        for (Annotation annotation : annotations) {
            String name = annotation.annotationType().getSimpleName();
            if (NULL_MARKED.contains(name)) {
                return true;
            }
            if (NULL_UNMARKED.contains(name)) {
                return false;
            }
        }
        return null;
    }

    private static boolean hasAnyOf(Annotation[] onComponent, Annotation[] onType, Set<String> names) {
        for (Annotation annotation : onComponent) {
            if (names.contains(annotation.annotationType().getSimpleName())) {
                return true;
            }
        }
        for (Annotation annotation : onType) {
            if (names.contains(annotation.annotationType().getSimpleName())) {
                return true;
            }
        }
        return false;
    }

    /** The TypeScript name for {@code c}: its simple name, or a longer one when another class already has it. */
    private String claim(Class<?> c) {
        String simple = c.getSimpleName().isEmpty() ? "Anonymous" : c.getSimpleName();
        String name = simple;
        if (taken.contains(name)) {
            String binary = c.getPackageName().isEmpty() ? c.getName() : c.getName().substring(c.getPackageName().length() + 1);
            name = binary.replace('$', '_');
        }
        if (taken.contains(name)) {
            name = c.getName().replace('.', '_').replace('$', '_');
        }
        for (int i = 2; taken.contains(name); i++) {
            name = simple + i;
        }
        taken.add(name);
        names.put(c, name);
        return name;
    }
}
